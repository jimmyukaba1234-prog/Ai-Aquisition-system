import { useEffect, useMemo, useState } from 'react';
import {
  LuPhone, LuMessageCircle, LuMail, LuPencil, LuTrash2, LuSparkles, LuCheck, LuUndo2, LuMapPin, LuBriefcase, LuHeart, LuHand, LuCalendar,
} from 'react-icons/lu';
import { useStore, can } from '../store.jsx';
import { Avatar, Badge, Button, Confirm, Drawer, FollowBadge, Segmented } from '../components/ui.jsx';
import GuestForm from './GuestForm.jsx';
import { fetchTalkingPoints } from '../lib/ai.js';
import { STAGES, OUTCOMES, CHANNELS, today, fullName, dayOf, daysBetween, followupDue } from '../lib/journey.js';
import { displayPhone, fmtDate, timeAgo, waLink, cls } from '../lib/format.js';

export default function GuestDrawer({ id, onClose }) {
  const { data } = useStore();
  const g = data?.guests.find((x) => x.id === id);
  return (
    <Drawer open={!!g} onClose={onClose} label={g ? fullName(g) : 'Guest'} width={720}>
      {g && <GuestDetail key={g.id} g={g} onClose={onClose} />}
    </Drawer>
  );
}

function GuestDetail({ g, onClose }) {
  const store = useStore();
  const { data, updateGuest, logFollowup, deleteGuest } = store;
  const { profiles, settings, followups, me } = data;
  const history = useMemo(() => followups.filter((f) => f.guest_id === g.id), [followups, g.id]);
  const [edit, setEdit] = useState(false);
  const [del, setDel] = useState(false);
  const [tp, setTp] = useState(null);
  const [tpBusy, setTpBusy] = useState(false);
  const [notes, setNotes] = useState(g.notes || '');
  const canEdit = can(me, 'editGuest');
  const team = profiles.filter((p) => ['admin', 'followup', 'acquisition'].includes(p.role) && p.active !== false);
  const name = (uid) => profiles.find((p) => p.id === uid)?.full_name || 'Someone';
  useEffect(() => setNotes(g.notes || ''), [g.notes]);

  async function talking() {
    setTpBusy(true);
    try { setTp(await fetchTalkingPoints(g, data)); } finally { setTpBusy(false); }
  }

  return (
    <div className="gd">
      <header className="gd-head">
        <Avatar name={fullName(g)} size={58} />
        <div className="gd-id">
          <h2 className="serif">{fullName(g)}</h2>
          <div className="gd-meta">
            <FollowBadge g={g} settings={settings} />
            {g.would_join && <Badge tone={g.would_join === 'Yes' ? 'good' : 'info'} dot={false}>Would join: {g.would_join}</Badge>}
            <span>First visit {fmtDate(g.first_visit, { year: true })}{g.visit_count > 1 ? ` · ${g.visit_count} visits` : ''}</span>
          </div>
        </div>
      </header>

      <div className="gd-actions">
        {g.phone && <a className="btn btn-primary" href={`tel:${g.phone}`}><LuPhone className="btn-ic" />Call {displayPhone(g.phone)}</a>}
        {g.phone && <a className="btn" href={waLink(g.phone)} target="_blank" rel="noopener"><LuMessageCircle className="btn-ic" />WhatsApp</a>}
        {g.email && <a className="btn" href={`mailto:${g.email}`}><LuMail className="btn-ic" />Email</a>}
        <span className="grow" />
        {canEdit && <Button variant="ghost" icon={LuPencil} onClick={() => setEdit(true)}>Edit</Button>}
        {can(me, 'deleteGuest') && <Button variant="ghost-danger" icon={LuTrash2} onClick={() => setDel(true)} aria-label="Delete guest" />}
      </div>

      <div className="gd-assign">
        <span>Assigned to</span>
        <select value={g.assigned_to || ''} disabled={!canEdit} onChange={(e) => updateGuest(g.id, { assigned_to: e.target.value || null }, 'Assignment updated')}>
          <option value="">Not assigned</option>
          {team.map((p) => <option key={p.id} value={p.id}>{p.full_name || p.email}</option>)}
        </select>
        {!g.followed_up_at && <span className="muted small"><LuCalendar aria-hidden /> Call by {fmtDate(followupDue(g, settings), { year: false })}</span>}
      </div>

      <section className="gd-sec">
        <h4>Journey</h4>
        <Journey g={g} canEdit={canEdit} departments={settings.departments || []} />
      </section>

      <section className="gd-sec gd-ai">
        <div className="gd-ai-h">
          <h4><LuSparkles aria-hidden /> Talking points</h4>
          <Button size="sm" onClick={talking} disabled={tpBusy}>{tpBusy ? 'Thinking…' : tp ? 'Refresh' : 'Prepare me for this call'}</Button>
        </div>
        {tp ? (
          <div className="tp">
            <p className="tp-open">“{tp.opener}”</p>
            <ul>{(tp.points || []).map((p, i) => <li key={i}>{p}</li>)}</ul>
            <p><b>Next step:</b> {tp.next_step}</p>
            {tp.suggested_department && <p><b>Department that may fit:</b> {tp.suggested_department}</p>}
            <p className="muted small">{tp.source === 'groq' ? 'Generated by Groq AI' : 'Suggested by built-in rules'} from the guest card and follow-up history. Prayer requests are never sent to the AI.</p>
          </div>
        ) : <p className="muted small">Get a suggested opening line, talking points and next step, based on what they shared on their card.</p>}
      </section>

      {can(me, 'logCall') && (
        <section className="gd-sec">
          <h4>Log a follow-up</h4>
          <LogForm g={g} onLog={logFollowup} />
        </section>
      )}

      <section className="gd-sec">
        <h4>Follow-up history <span className="muted">({history.length})</span></h4>
        {history.length ? (
          <ol className="hist">
            {history.map((f) => (
              <li key={f.id} className={cls('hist-i', f.outcome === 'Reached' && 'ok')}>
                <span className="hist-dot" />
                <div>
                  <div className="hist-top"><b>{f.outcome}</b><span>{f.channel} · {name(f.by_user)} · {timeAgo(f.created_at)}</span></div>
                  {f.notes && <p>{f.notes}</p>}
                  {f.next_step_date && <p className="small muted">Next step: {fmtDate(f.next_step_date)}</p>}
                </div>
              </li>
            ))}
          </ol>
        ) : <p className="muted small">No follow-ups logged yet.</p>}
      </section>

      <section className="gd-sec">
        <h4>From the guest card</h4>
        <div className="facts">
          <Fact icon={LuMapPin} label="Address" value={[g.house_no, g.street, g.area, g.town, g.lga].filter(Boolean).join(', ')} />
          <Fact icon={LuMapPin} label="Nearest bus stop" value={g.bus_stop} />
          <Fact label="Gender · Age" value={[g.gender, g.age_range].filter(Boolean).join(' · ')} />
          <Fact label="Status" value={g.marital_status} />
          <Fact icon={LuBriefcase} label="Sector · Occupation" value={[g.sector, g.occupation].filter(Boolean).join(' · ')} />
          <Fact icon={LuMail} label="Email" value={g.email} />
          <Fact label="Heard about us via" value={(g.heard_via || []).join(', ')} />
          <Fact label="Interests" value={(g.interests || []).join(', ')} />
        </div>
        {g.needs && <div className="quote"><LuHeart aria-hidden /><div><b>Needs &amp; aspirations</b><p>{g.needs}</p></div></div>}
        {g.prayer_request && <div className="quote"><LuHand aria-hidden /><div><b>Prayer request</b><p>{g.prayer_request}</p></div></div>}
      </section>

      <section className="gd-sec">
        <h4>Team notes</h4>
        <textarea className="notes" value={notes} disabled={!canEdit} placeholder="Anything the team should know…" onChange={(e) => setNotes(e.target.value)} onBlur={() => notes !== (g.notes || '') && updateGuest(g.id, { notes }, 'Notes saved')} />
      </section>

      <GuestForm open={edit} guest={g} onClose={() => setEdit(false)} onSaved={() => setEdit(false)} />
      <Confirm open={del} onClose={() => setDel(false)} title="Delete this guest?" confirmLabel="Delete guest"
        body={`${fullName(g)} and their follow-up history will be permanently removed. This can't be undone.`}
        onConfirm={async () => { await deleteGuest(g.id); onClose(); }} />
    </div>
  );
}

const Fact = ({ icon: Icon, label, value }) => (
  <div className="fact"><span>{Icon && <Icon aria-hidden />}{label}</span><b>{value || '—'}</b></div>
);

function Journey({ g, canEdit, departments }) {
  const { updateGuest } = useStore();
  const [openKey, setOpenKey] = useState(null);
  const [date, setDate] = useState(today());
  const [dept, setDept] = useState(g.department || departments[0] || '');

  async function mark(s) {
    const patch = s.key === 'followed_up' ? { followed_up_at: new Date(date + 'T12:00:00').toISOString() } : { [s.field]: date };
    if (s.key === 'department') patch.department = dept;
    await updateGuest(g.id, patch, `${s.label}: marked`);
    setOpenKey(null);
  }
  async function undo(s) {
    const patch = { [s.field]: null };
    if (s.key === 'department') patch.department = null;
    await updateGuest(g.id, patch, `${s.label}: cleared`);
  }

  return (
    <ol className="journey">
      {STAGES.map((s, i) => {
        const v = g[s.field];
        const done = !!v;
        const prevDone = i === 0 || !!g[STAGES[i - 1].field];
        return (
          <li key={s.key} className={cls('j-step', done && 'done', !done && prevDone && 'next')}>
            <span className="j-dot">{done ? <LuCheck aria-hidden /> : i + 1}</span>
            <div className="j-body">
              <div className="j-top">
                <b>{s.label}{s.key === 'department' && g.department ? ` · ${g.department}` : ''}</b>
                {done ? (
                  <span className="j-date">
                    {fmtDate(dayOf(v), { year: true })}
                    {i > 0 && <em>{daysBetween(g.first_visit, dayOf(v))} days after first visit</em>}
                    {i > 0 && canEdit && <button className="icon-btn sm" title="Undo" aria-label={`Undo ${s.label}`} onClick={() => undo(s)}><LuUndo2 /></button>}
                  </span>
                ) : canEdit && i > 0 && openKey !== s.key && (
                  <Button size="sm" variant={prevDone ? 'primary' : 'default'} onClick={() => { setOpenKey(s.key); setDate(today()); }}>Mark done</Button>
                )}
              </div>
              {openKey === s.key && (
                <div className="j-form">
                  <label>Date <input type="date" value={date} max={today()} min={g.first_visit} onChange={(e) => setDate(e.target.value)} /></label>
                  {s.key === 'department' && (
                    <label>Department
                      <select value={dept} onChange={(e) => setDept(e.target.value)}>{departments.map((d) => <option key={d}>{d}</option>)}</select>
                    </label>
                  )}
                  <Button size="sm" variant="primary" icon={LuCheck} onClick={() => mark(s)}>Save</Button>
                  <Button size="sm" variant="ghost" onClick={() => setOpenKey(null)}>Cancel</Button>
                </div>
              )}
            </div>
          </li>
        );
      })}
    </ol>
  );
}

function LogForm({ g, onLog }) {
  const [channel, setChannel] = useState('Call');
  const [outcome, setOutcome] = useState('');
  const [notes, setNotes] = useState('');
  const [next, setNext] = useState('');
  const [busy, setBusy] = useState(false);
  async function submit(e) {
    e.preventDefault();
    if (!outcome) return;
    setBusy(true);
    try { await onLog({ guest_id: g.id, channel, outcome, notes: notes.trim() || null, next_step_date: next || null }); setOutcome(''); setNotes(''); setNext(''); }
    finally { setBusy(false); }
  }
  return (
    <form className="log" onSubmit={submit}>
      <Segmented small value={channel} onChange={setChannel} options={CHANNELS.map((c) => ({ key: c, label: c }))} />
      <div className="chips">
        {OUTCOMES.map((o) => <button type="button" key={o} className={cls('chip', outcome === o && 'on', o === 'Reached' && 'chip-good')} onClick={() => setOutcome(o)}>{o}</button>)}
      </div>
      <textarea value={notes} onChange={(e) => setNotes(e.target.value)} placeholder="What did they say? Any prayer point, question or next step…" rows={2} />
      <div className="log-row">
        <label className="small">Call back / next step on <input type="date" value={next} min={today()} onChange={(e) => setNext(e.target.value)} /></label>
        <span className="grow" />
        <Button variant="primary" type="submit" disabled={!outcome || busy}>{busy ? 'Saving…' : 'Save follow-up'}</Button>
      </div>
      {outcome === 'Reached' && !g.followed_up_at && <p className="small muted">Saving as “Reached” marks {g.other_names?.split(' ')[0] || 'this guest'} as followed up.</p>}
    </form>
  );
}
